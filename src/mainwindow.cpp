// Event for reserving spot and declaring checkin time and all
void MainWindow::onSpotReservationConfirmed(unsigned long floorId, int spotId, const QString &vehicleReg)
{
    QString reg = vehicleReg.isEmpty() ? "UNREGISTERED" : vehicleReg;

    int result = structures.SelectSpace(reg.toStdString(), floorId, spotId, currentCustomerId);

    if (result == 0) {
        qDebug() << "[SUCCESS] Floor" << (floorId + 1) << "Spot" << (spotId + 1) << "assigned to vehicle:" << reg;
        QMessageBox::information(
            this,
            "Reservation Confirmed",
            QString("Spot %1 on Floor %2 has been successfully reserved for vehicle:\n%3")
                .arg(spotId + 1)
                .arg(floorId + 1)
                .arg(reg)
        );
    } else {
        qDebug() << "[ERROR] Could not reserve Floor" << (floorId + 1) << "Spot" << (spotId + 1);
        QMessageBox::critical(
            this,
            "Error",
            QString("Could not reserve Floor %1 Spot %2. It may already be occupied.").arg(floorId + 1).arg(spotId + 1)
        ); // INcase the reservation fails (Hoever this part may not be reached since if occupied it would be already flagged earluer on as the spot is not clickable)
    }
}
